import { z } from "zod";

export const journalSettingsSchema = z.object({
  journalName: z.string().min(2, "Journal name is required").optional(),
  shortName: z.string().optional().or(z.literal("")),
  issn: z.string().optional().or(z.literal("")),
  publisherName: z.string().optional().or(z.literal("")),
  description: z.string().optional().or(z.literal("")),
  publicationFrequency: z.string().optional().or(z.literal("")),
  email: z.string().email().optional().or(z.literal("")),
  phone: z.string().optional().or(z.literal("")),
  address: z.string().optional().or(z.literal("")),
  logo: z.string().optional().or(z.literal("")),
  primaryColor: z.string().optional().or(z.literal("")),
  secondaryColor: z.string().optional().or(z.literal("")),
  paymentFee: z.coerce.number().min(0).optional(),
  paymentCurrency: z.string().optional().or(z.literal("")),
  paymentProvider: z.string().optional().or(z.literal("")),
  paymentLink: z.string().url("Must be a valid URL").optional().or(z.literal("")),
  paymentQrCode: z.string().optional().or(z.literal("")),
  paymentInstructions: z.string().optional().or(z.literal("")),
  mailgunApiKey: z.string().optional().or(z.literal("")),
  mailgunDomain: z.string().optional().or(z.literal("")),
  mailgunUrl: z.string().optional().or(z.literal("")),
  mailgunFrom: z.string().optional().or(z.literal("")),
});
